import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

export async function generateApi() {
  const openapiPath = path.resolve(__dirname, '../../docs/openapi.json');
  if (!fs.existsSync(openapiPath)) {
    throw new Error(`OpenAPI schema not found at ${openapiPath}`);
  }

  const rawJson = fs.readFileSync(openapiPath, 'utf-8');
  const openapiDoc = JSON.parse(rawJson);

  // 1. Generate schema.gen.ts
  const fileUrl = new URL('../../docs/openapi.json', import.meta.url);
  const ast = await openapiTS(fileUrl);
  const typeDefinitions = astToString(ast);

  const apiDir = path.resolve(__dirname, '../src/api');
  fs.mkdirSync(apiDir, { recursive: true });

  const schemaGenPath = path.join(apiDir, 'schema.gen.ts');
  const banner = '/**\n * Auto-generated by scripts/gen-api.js from docs/openapi.json.\n * DO NOT EDIT MANUALLY.\n */\n\n';
  const schemaContent = banner + typeDefinitions;

  // 2. Generate limits.ts
  const maxLength =
    openapiDoc?.components?.schemas?.AnalyzeRequest?.properties?.sql?.maxLength ?? 50000;
  const limitsContent = `/**\n * Auto-generated by scripts/gen-api.js from docs/openapi.json.\n * DO NOT EDIT MANUALLY.\n */\n\nexport const MAX_SQL_LENGTH = ${maxLength};\n`;
  const limitsPath = path.join(apiDir, 'limits.ts');

  return {
    schemaGenPath,
    schemaContent,
    limitsPath,
    limitsContent,
  };
}

// If run directly
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try {
    const { schemaGenPath, schemaContent, limitsPath, limitsContent } = await generateApi();
    fs.writeFileSync(schemaGenPath, schemaContent, 'utf-8');
    fs.writeFileSync(limitsPath, limitsContent, 'utf-8');
    console.log(`Successfully generated:\n - ${schemaGenPath}\n - ${limitsPath}`);
  } catch (err) {
    console.error('Error generating API schemas:', err);
    process.exit(1);
  }
}

